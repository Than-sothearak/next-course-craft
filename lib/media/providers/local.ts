import { randomUUID } from "node:crypto";
import { constants } from "node:fs";
import { link, lstat, mkdir, open, realpath, unlink } from "node:fs/promises";
import { dirname, isAbsolute, join, parse, relative, resolve, sep } from "node:path";
import { Readable } from "node:stream";
import { DashboardError } from "@/lib/dashboard/rules";
import type { StorageFile, StorageProvider, StorageUpload } from "./types";

export function localStorageDirectory(directory?: string) {
  const configured = directory ?? process.env.MEDIA_LOCAL_DIRECTORY;
  if (!configured || !isAbsolute(configured)) throw new DashboardError("Set MEDIA_LOCAL_DIRECTORY to an absolute persistent upload directory.", 503);
  const root = resolve(configured);
  const fromApp = relative(process.cwd(), root);
  if (root === parse(root).root || fromApp === "" || (!fromApp.startsWith(`..${sep}`) && fromApp !== ".." && !isAbsolute(fromApp))) {
    throw new DashboardError("The upload directory must be outside the application directory.", 503);
  }
  return root;
}

function hasCode(error: unknown, code: string) {
  return typeof error === "object" && error !== null && "code" in error && error.code === code;
}

export class LocalStorageProvider implements StorageProvider {
  constructor(private readonly directory?: string) {}

  private async path(key: string, create = false) {
    // Keys are generated by the server; original filenames are never paths.
    if (!/^[a-zA-Z0-9_-]+(?:\/[a-zA-Z0-9_-]+)*$/.test(key) || key.length > 512) throw new DashboardError("Invalid storage key.", 400);
    const root = localStorageDirectory(this.directory);
    if (create) await mkdir(root, { recursive: true, mode: 0o700 });
    if ((await lstat(root)).isSymbolicLink()) throw new DashboardError("The upload directory cannot be a symbolic link.", 503);
    const canonicalRoot = await realpath(root);
    let parent = canonicalRoot;
    for (const segment of key.split("/").slice(0, -1)) {
      parent = join(parent, segment);
      if (create) await mkdir(parent, { mode: 0o700 }).catch((error) => { if (!hasCode(error, "EEXIST")) throw error; });
      const info = await lstat(parent);
      if (!info.isDirectory() || info.isSymbolicLink()) throw new DashboardError("Unsafe upload directory.", 503);
    }
    if (await realpath(parent) !== parent) throw new DashboardError("Unsafe upload directory.", 503);
    return join(parent, key.split("/").at(-1)!);
  }

  async upload({ key, body, size, signal }: StorageUpload) {
    const target = await this.path(key, true);
    const temporary = join(dirname(target), `pending-${randomUUID()}`);
    const handle = await open(temporary, constants.O_WRONLY | constants.O_CREAT | constants.O_EXCL | constants.O_NOFOLLOW, 0o600);
    try {
      let count = 0;
      const chunks = Buffer.isBuffer(body) ? [body] : Readable.fromWeb(body as import("node:stream/web").ReadableStream<Uint8Array>, { signal });
      for await (const chunk of chunks) {
        signal?.throwIfAborted();
        const bytes = Buffer.from(chunk);
        count += bytes.length;
        if (count > size) throw new DashboardError("The uploaded file exceeds its validated size.", 413);
        await handle.writeFile(bytes);
      }
      signal?.throwIfAborted();
      if (count !== size) throw new DashboardError("The uploaded file does not match its validated size.", 400);
      await handle.sync();
      await handle.close();
      // Atomic publication without replacing a concurrent or already completed upload.
      await link(temporary, target).catch((error) => {
        if (hasCode(error, "EEXIST")) throw new DashboardError("This file has already been uploaded. Complete the upload or start a new one.", 409);
        throw error;
      });
    } finally {
      await handle.close().catch(() => undefined);
      await unlink(temporary);
    }
  }

  private async openFile(key: string) {
    try {
      const handle = await open(await this.path(key), constants.O_RDONLY | constants.O_NOFOLLOW | constants.O_NONBLOCK);
      const info = await handle.stat();
      if (!info.isFile() || info.nlink !== 1) {
        await handle.close();
        throw new DashboardError("Unsafe media file.", 503);
      }
      return { handle, info };
    } catch (error) {
      if (hasCode(error, "ENOENT")) throw new DashboardError("The media file is missing from local storage.", 404);
      throw error;
    }
  }

  async metadata(key: string) {
    const { handle, info } = await this.openFile(key);
    await handle.close();
    return { size: info.size };
  }

  async read(file: StorageFile, options: { range?: string; signal?: AbortSignal } = {}) {
    const { handle, info } = await this.openFile(file.key);
    let start = 0;
    let end = info.size - 1;
    const headers = new Headers({ "Content-Type": file.contentType, "Accept-Ranges": "bytes" });
    if (options.range) {
      const match = /^bytes=(\d*)-(\d*)$/.exec(options.range);
      if (match && (match[1] || match[2])) {
        start = match[1] ? Number(match[1]) : Math.max(0, info.size - Number(match[2]));
        end = match[1] && match[2] ? Math.min(Number(match[2]), end) : end;
      } else start = -1;
      if (!Number.isSafeInteger(start) || !Number.isSafeInteger(end) || start < 0 || start > end || start >= info.size) {
        await handle.close();
        headers.set("Content-Range", `bytes */${info.size}`);
        return new Response(null, { status: 416, headers });
      }
      headers.set("Content-Range", `bytes ${start}-${end}/${info.size}`);
    }
    headers.set("Content-Length", String(end - start + 1));
    if (!info.size) { await handle.close(); return new Response(null, { headers }); }
    const stream = handle.createReadStream({ start, end, autoClose: true, signal: options.signal });
    return new Response(Readable.toWeb(stream) as ReadableStream<Uint8Array>, { status: options.range ? 206 : 200, headers });
  }

  async delete(key: string) {
    try { await unlink(await this.path(key)); }
    catch (error) { if (!hasCode(error, "ENOENT")) throw error; }
  }
}
